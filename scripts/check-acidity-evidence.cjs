const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('coffee-jolka-app.js','utf8');
const c = {products:[]}; vm.createContext(c);
vm.runInContext(source.slice(source.indexOf('  const WEIGHTS ='),source.indexOf('  const state =')),c);
vm.runInContext(fs.readFileSync('coffee-catalogues/simplecoffee.js','utf8'),c);
const products=c.CX_COFFEE_CATALOGUES.simplecoffee.products;
const find=path=>products.find(p=>p.url==='https://simplecoffee.sk/produkt/'+path+'/');
const ride=find('coffee-ride');
assert.equal(ride.acidity,null);
assert.deepEqual(Array.from(ride.acidityRange),[1,2]);
assert(c.unmet(ride,{acidity:'none'}).includes('acidity'),'Mild-to-medium is not verified lowest acidity.');
assert(!c.unmet(ride,{acidity:'mild'}).includes('acidity'));
assert(c.unmet(ride,{acidity:'bright'}).includes('acidity'),'Range must fully meet the preference.');
const kenya=find('zrnkova-kava-z-keni');
assert(c.unmet(kenya,{acidity:'none'}).includes('acidity'));
assert(!c.unmet(kenya,{acidity:'bright'}).includes('acidity'));
assert.equal(find('zrnkova-kava-z-burundi').acidity,2);
assert.equal(find('zrnkova-kava-z-dominikanske-republiky').acidity,2);
assert.equal(find('po-svojom').acidity,null,'Do not assign the acidity of the compared Najka to Po svojom.');
assert(!c.unmet(find('zrnkova-bezkofeinova-kava-decaf'),{acidity:'none',caffeine:'no'}).length);
const evidence=JSON.parse(fs.readFileSync('audit-evidence/20261015-simplecoffee-acidity.json','utf8'));
assert.equal(evidence.products.length,25);
assert.equal(find('zrnkova-kava-oro-nero').taste.fruity,0,'Negated citrus flavour is not a positive preference.');
assert.equal(kenya.taste.chocolate,0,'Comparing Kenya to chocolate Brazil does not give Kenya chocolate notes.');
assert(!find('zrnkova-kava-oro-nero').notes.some(n=>/citrus/i.test(n)));
const wave=find('simple-new-wave-espresso-blend');
assert.deepEqual(Array.from(wave.acidityRange),[1,2],'Conflicting official descriptions must not become a single point.');
assert(c.unmet(wave,{prep:'automat'}).includes('prep'));
assert.equal(wave.variants[0].grams,200);
assert.equal(wave.variants[0].price,7.9);
console.log('PASS: source acidity, explicit range, unknown comparison, decaf and bright/low filters.');
