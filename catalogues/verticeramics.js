globalThis.CX_CATALOGUES.verticeramics.reply = function reply(text) {
  const normalize = value => String(value || '').normalize('NFD').replace(/\p{Diacritic}/gu,'').toLowerCase();
  const question = normalize(text);
  const products = globalThis.CX_CATALOGUES.verticeramics.products.filter(row => row.available);
  const facts = product => product.source.selectionTraitsEvidence;
  const line = product => `${product.name} · ${product.volume} · ${product.price}. Rozmery ${facts(product).dimensions}.\n${product.url}`;
  const named = products.filter(product =>
    new RegExp(`(?:^|\\D)${product.sku}(?:$|\\D)`).test(question) || question.includes(normalize(product.name)));
  if (/mikrovln|sporak|\brur[aeuy]\b|ohn|mraznic/.test(question)) {
    return 'V údajoch k týmto hrnčekom nemám potvrdenie pre uvedený typ ohrevu alebo skladovania. Overte si ho priamo u výrobcu.';
  }
  if (/umyv|umyvat|cistit|starost/.test(question)) {
    const care = 'Výrobca uvádza, že hrnčeky možno umývať v umývačke, no pre dlhší lesk glazúry odporúča ručné umývanie.';
    return named.length ? care+'\n'+named.map(line).join('\n\n') : care;
  }

  if (/porovn/.test(question) && named.length < 2) {
    return 'Napíšte dva kódy hrnčekov. Môžete skúsiť napríklad 452 a 1340. Porovnám objem, rozmery a cenu.';
  }

  const price = question.match(/\bdo\s*(\d+(?:[.,]\d+)?)\s*(?:eur\b|€)/);
  const maxPrice = price ? Number(price[1].replace(',','.')) : Infinity;
  const min = question.match(/\b(nad|aspon|od)\s*(\d+)\s*ml\b/);
  const max = question.match(/\bdo\s*(\d+)\s*ml\b/);
  const target = !min && !max ? question.match(/\b(\d+)\s*ml\b/) : null;
  const handle = /bez\s+usk/.test(question) ? false : /s\s+usk/.test(question) ? true : null;
  const espresso = /espress/.test(question);
  const style = /dark cotton/.test(question) ? /dark cotton/ : /limoncello/.test(question) ? /limoncello/ :
    /sakura/.test(question) ? /sakura/ : /\bcotton\b/.test(question) ? /(?<!dark )cotton/ : /\bcookie\b/.test(question) ? /cookie/ : null;

  const matching = (named.length ? named : products).filter(product => {
    const volumeGuess = product.volume.match(/\d+/g).map(Number);
    const floor = volumeGuess[0];
    const ceiling = volumeGuess.at(-1);
    return product.priceAmount <= maxPrice && (handle === null || handle === product.source.withHandle) &&
      (!espresso || ceiling <= 100) && (!style || style.test(normalize(product.name))) &&
      (!min || (min[1] === 'nad' ? floor > Number(min[2]) : floor >= Number(min[2]))) &&
      (!max || ceiling <= Number(max[1])) && (!target || (floor <= Number(target[1]) && ceiling >= Number(target[1])));
  });
  if (named.length || price || min || max || target || handle !== null || espresso || style) {
    if (!matching.length) return 'V tejto ukážke som pre zadané podmienky nenašiel hrnček. Skúste zmeniť objem, tvar alebo cenu.';
    return matching.slice(0,3).map(line).join('\n\n') + '\nObjem je približný, pretože keramika je ručne točená.';
  }
  return 'Vyberám z keramických hrnčekov verti ceramics. Napíšte objem, či chcete uško, kolekciu alebo kódy dvoch hrnčekov, ktoré chcete porovnať.';
};
