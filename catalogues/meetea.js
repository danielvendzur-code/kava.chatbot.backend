// Catalogue-specific reply shared by the tea demo's online draft and offline fallback.
globalThis.CX_CATALOGUES.meetea.reply = function reply(text) {
  const normal = value => String(value || '').normalize('NFD').replace(/\p{Diacritic}/gu, '').toLowerCase();
  const question = normal(text);
  const products = globalThis.CX_CATALOGUES.meetea.products.filter(product => product.available);
  const productText = product => `${product.name} · ${product.kind} · ${product.volume} za ${product.price}.\n${product.description}\n${product.url}`;
  const limit = question.match(/\b(?:do|max(?:imalne)?)\s*(\d+(?:[ ]\d{3})?)\s*(kc|czk|korun|eur|€)?/);
  if (limit && /eur|€/.test(limit[2] || '')) return 'Ceny v ukázce jsou v Kč. Zadejte prosím limit v Kč.';
  const withinLimit = product => !limit || product.priceAmount <= Number(limit[1].replace(/ /g, ''));
  const named = products.filter(product => {
    const name = normal(product.name);
    return question.includes(name) ||
      (name.length > 7 && question.includes(name.replace(/\s\d{4}$/, '')));
  });
  if (/priprav|zalit|teplot|luhov/.test(question)) {
    return named.length ? `Pro konkrétní přípravu se podívejte na stránku čaje ${named[0].name}: ${named[0].url}`
      : 'Napište název čaje. Ukážu vám jeho stránku s podrobnostmi.';
  }
  if (/kofein|alerg|lec|ucink|tehot|spank|nespav|bez\s+\p{L}{3,}/u.test(question)) {
    return 'Pro tyto čaje nemám ověřené údaje k tomuto požadavku. Můžu vybírat podle chuti, druhu a ceny za 50 g.';
  }
  if (named.length) {
    const matches = named.filter(withinLimit);
    return matches.length ? matches.map(productText).join('\n\n')
      : 'Uvedený čaj se v balení 50 g do tohoto limitu nevejde.';
  }
  const group = [
    [/oolong|polozelen/, 'meeteaOolong'],
    [/cern\p{L}* caj|cerven\p{L}* caj/u, 'meeteaBlack'],
    [/shu|tmav\p{L}* caj|liubao|heicha/u, 'meeteaDark'],
    [/sheng|zrajici|pu.?er/, 'meeteaSheng']
  ];
  const terms = [
    [/jasmin|kvetin|letni louk/, 'jasmin'],
    [/kaka/, 'kakao'],
    [/kav/, 'kava'],
    [/mang/, 'mango'],
    [/povidl/, 'povidla'],
    [/skor/, 'skorice'],
    [/medov/, 'med'],
    [/vlas.*orech/, 'vlasske orechy'],
    [/kafr/, 'kafr'],
    [/bezov.*kvet/, 'bezovy kvet']
  ];
  const type = group.find(([pattern]) => pattern.test(question))?.[1];
  const note = terms.find(([pattern]) => pattern.test(question))?.[1];
  if (!type && !note && !limit) {
    return 'V ukázce Meetea jsou oolongy, černé čaje, sheng puer a tmavé čaje. Zkuste napsat druh, chuťový tón nebo dva názvy čajů k porovnání.';
  }
  const matches = products.filter(product => withinLimit(product) &&
    (!type || product.source.selectionTraits.careUse === type) &&
    (!note || normal(product.description).includes(note)));
  if (!matches.length) return 'Pro tuto kombinaci jsem v ukázce Meetea nenašel čaj. Zkuste jiný chuťový tón nebo limit.';
  return matches.slice(0, 2).map(productText).join('\n\n') + '\nCena platí za 50 g. Balení vyberte na stránce e-shopu.';
};
